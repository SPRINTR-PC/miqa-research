#!/usr/bin/env python3
"""Generate the MIRES SFTP Uploader colour brushes from the Django design tokens.

Reads the `:root` (light) and `.dark` blocks of src/MiqaResearch/static/css/mires.css and writes
src/dotnet/MiresSftpUploader/Themes/MiresTheme.axaml: one ResourceDictionary per theme variant holding
SolidColorBrush resources named M<Token>. The `.dark` block only overrides some tokens, as in CSS, so dark is
light overlaid with `.dark`.

One deliberate deviation: the Django light-mode `primary-foreground` (hsl 151 80% 95%, near white) on `primary`
(hsl 277 100% 75%) has a contrast ratio of about 1.8, so in light mode the uploader uses the dark-mode
foreground, which gives about 9.

Usage: tools/generate_uploader_theme.py [--check]   (--check fails if the committed file is out of date)
"""
import colorsys
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSS = ROOT / "src/MiqaResearch/static/css/mires.css"
OUT = ROOT / "src/dotnet/MiresSftpUploader/Themes/MiresTheme.axaml"

# Brush name -> CSS token (without the `--color-` prefix and `-parts` suffix).
TOKENS = {
    "MBackground": "background",
    "MForeground": "foreground",
    "MCard": "card",
    "MPopover": "popover",
    "MPrimary": "primary",
    "MPrimaryFg": "primary-foreground",
    "MSecondary": "secondary",
    "MMuted": "muted",
    "MMutedFg": "muted-foreground",
    "MAccent": "accent",
    "MAccentFg": "accent-foreground",
    "MDestructive": "destructive",
    "MBorder": "border",
    "MElevated": "surface-elevated",
    "MSunken": "surface-sunken",
    "MSuccess": "chart-success",
    "MWarning": "chart-warning",
    "MInfo": "chart-info",
}


def block(css: str, selector: str) -> dict:
    match = re.search(re.escape(selector) + r"\s*\{(.*?)\n\}", css, re.S)
    if not match:
        sys.exit(f"selector {selector} not found in {CSS}")
    parts = {}
    for name, value in re.findall(r"--color-([a-z0-9-]+)-parts:\s*([^;]+);", match.group(1)):
        numbers = re.findall(r"[\d.]+", value)
        if len(numbers) == 3:
            parts[name] = tuple(float(n) for n in numbers)
    return parts


def to_hex(hsl) -> str:
    h, s, l = hsl[0] / 360, hsl[1] / 100, hsl[2] / 100
    r, g, b = colorsys.hls_to_rgb(h, l, s)
    return "#{:02X}{:02X}{:02X}".format(round(r * 255), round(g * 255), round(b * 255))


def render() -> str:
    css = CSS.read_text()
    light = block(css, ":root")
    dark = {**light, **block(css, ".dark")}
    # Contrast fix: see the module docstring.
    light["primary-foreground"] = dark["primary-foreground"]

    def dictionary(key: str, tokens: dict) -> str:
        lines = [f'        <ResourceDictionary x:Key="{key}">']
        for brush, token in TOKENS.items():
            lines.append(f'            <SolidColorBrush x:Key="{brush}">{to_hex(tokens[token])}</SolidColorBrush>')
        lines.append("        </ResourceDictionary>")
        return "\n".join(lines)

    return (
        '<ResourceDictionary xmlns="https://github.com/avaloniaui"\n'
        '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">\n'
        "    <!-- GENERATED by tools/generate_uploader_theme.py from src/MiqaResearch/static/css/mires.css. Do not edit. -->\n"
        "    <ResourceDictionary.ThemeDictionaries>\n"
        + dictionary("Dark", dark)
        + "\n"
        + dictionary("Light", light)
        + "\n    </ResourceDictionary.ThemeDictionaries>\n</ResourceDictionary>\n"
    )


def main() -> None:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT} is out of date; run tools/generate_uploader_theme.py")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)


if __name__ == "__main__":
    main()
