"""The De-identification Profile as data (ADR 0028).

Resolves the committed PS3.15 tables (`data/`, regenerated by
`generate_tables.py`) into one action per attribute for the fixed,
system-wide profile:

- Basic Application Level Confidentiality Profile (Table E.1-1), with the
  Retain Patient Characteristics, Retain Longitudinal Temporal Information
  with Full Dates, Retain Device Identity, Retain Institution Identity and
  Retain Safe Private options;
- every instance UID the table names (``U`` or ``K`` under Retain UIDs) is
  pseudonymized with the per-project HashUID instead of being retained;
- a descriptor allowlist (documented deviation, not Clean Descriptors);
- a local exception for GE (0009,xx0D) ``GEMS_PETD_01``.

Option cells marked ``C`` (clean) fall back to the Basic Profile action:
cleaning free text isn't implemented, so the conservative action wins.
"""
import enum
import json
import re
from functools import cache
from pathlib import Path

_DATA_DIR = Path(__file__).parent / "data"


class Action(enum.Enum):
    KEEP = "K"
    REMOVE = "X"
    EMPTY = "Z"
    DUMMY = "D"
    PSEUDONYMIZE_UID = "U"
    PARTICIPANT_PSEUDONYM = "P"


# Retention options applied, as (E.1-1 column, DCM code, code meaning)
APPLIED_OPTIONS: tuple[tuple[str, str, str], ...] = (
    ("retain_safe_private", "113111", "Retain Safe Private Option"),
    ("retain_device_identity", "113109", "Retain Device Identity Option"),
    ("retain_institution_identity", "113112", "Retain Institution Identity Option"),
    ("retain_patient_characteristics", "113108", "Retain Patient Characteristics Option"),
    ("retain_long_full_dates", "113106", "Retain Longitudinal Temporal Information Full Dates Option"),
)
BASIC_PROFILE_CODE = ("113100", "Basic Application Confidentiality Profile")

# Structural descriptors kept as-is (ADR 0028 deviation from Clean Descriptors)
DESCRIPTOR_ALLOWLIST: frozenset[int] = frozenset({
    0x00081030,  # StudyDescription
    0x0008103E,  # SeriesDescription
    0x00181030,  # ProtocolName
    0x00180015,  # BodyPartExamined
})

PARTICIPANT_PSEUDONYM_TAGS: frozenset[int] = frozenset({
    0x00100010,  # PatientName
    0x00100020,  # PatientID
})

# Local exceptions on top of Table E.3.10-1: (group, private creator, element offset)
LOCAL_SAFE_PRIVATE: frozenset[tuple[int, str, int]] = frozenset({
    (0x0009, "GEMS_PETD_01", 0x0D),  # GE post-injection datetime (SUV on reprocessed GE PET)
})

DEIDENTIFICATION_METHOD: tuple[str, ...] = (
    "PS3.15 Basic Profile",
    "Retain Patient Characteristics",
    "Retain Longitudinal Full Dates",
    "Retain Device Identity",
    "Retain Institution Identity",
    "Retain Safe Private + GE (0009,xx0D)",
    "UIDs replaced with per-project HashUID",
    "Deviation: Study/Series Description, Protocol",
    "Name, Body Part Examined kept uncleaned",
    "Deviation: SR Content Sequence kept, its text values too",
)

_TAG = re.compile(r"\(([0-9A-Fx]{4}),([0-9A-Fx]{4})\)")


def _load(name: str) -> list[dict]:
    with (_DATA_DIR / f"{name}.json").open(encoding="utf-8") as fh:
        return json.load(fh)["rows"]


def _resolve_basic(basic: str) -> Action:
    """Pick one action from a compound Basic Profile cell.

    Prefers the least destructive conformant choice: a UID is pseudonymized
    (``U``), otherwise a dummy keeps a Type 1 attribute present (``D``),
    otherwise an empty value keeps a Type 2 present (``Z``), else remove.
    """
    choices = set(basic.replace("*", "").split("/"))
    preference = (("U", Action.PSEUDONYMIZE_UID), ("D", Action.DUMMY), ("Z", Action.EMPTY))
    for letter, action in preference:
        if letter in choices:
            return action
    return Action.REMOVE


def _resolve_row(row: dict) -> Action:
    if "U" in row["basic"] or row["retain_uids"] == "K":
        return Action.PSEUDONYMIZE_UID
    if any(row[column] == "K" for column, _, _ in APPLIED_OPTIONS):
        return Action.KEEP
    return _resolve_basic(row["basic"])


@cache
def public_actions() -> tuple[dict[int, Action], tuple[tuple[int, int, Action], ...]]:
    """(exact tag -> action, repeating-group masks as (mask, value, action))."""
    exact: dict[int, Action] = {}
    masked: list[tuple[int, int, Action]] = []
    for row in _load("table_E.1-1"):
        match = _TAG.fullmatch(row["tag"])
        if match is None:
            continue  # "(gggg,eeee) where gggg is odd": private attributes, handled separately
        group, element = match.groups()
        action = _resolve_row(row)
        if "x" in group or "x" in element:
            # Repeating groups such as (50xx,xxxx) and (60xx,3000)
            tag = group + element
            mask = int("".join("0" if c == "x" else "F" for c in tag), 16)
            value = int(tag.replace("x", "0"), 16)
            masked.append((mask, value, action))
        else:
            exact[int(group + element, 16)] = action
    for tag in DESCRIPTOR_ALLOWLIST:
        exact[tag] = Action.KEEP
    for tag in PARTICIPANT_PSEUDONYM_TAGS:
        exact[tag] = Action.PARTICIPANT_PSEUDONYM
    return exact, tuple(masked)


@cache
def safe_private_elements() -> frozenset[tuple[int, str, int]]:
    """(group, private creator, element offset) of every retained private attribute."""
    safe = set(LOCAL_SAFE_PRIVATE)
    for row in _load("table_E.3.10-1"):
        match = _TAG.fullmatch(row["tag"])
        if match is None:
            continue
        group, element = match.groups()
        safe.add((int(group, 16), row["private_creator"].strip(), int(element[2:], 16)))
    return frozenset(safe)


def action_for_public_tag(tag: int) -> Action:
    """The profile's action for a public (even-group) attribute; unlisted ones are kept."""
    exact, masked = public_actions()
    action = exact.get(tag)
    if action is not None:
        return action
    for mask, value, masked_action in masked:
        if tag & mask == value:
            return masked_action
    return Action.KEEP
